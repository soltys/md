/* Build-time helper (never shipped): packs the two big parse tables of one
 * tree-sitter grammar, zstd-compressed, into a C source file for md.exe.
 *
 *   ts_pack <out.c> <out.h> <id>
 *
 * Compiled once per grammar with MD_PARSER_C naming that grammar's original
 * parser.c, which is included below, so the tables are read exactly as the
 * C compiler laid them out. md.exe compiles an edited copy of parser.c in
 * which these tables are empty (no space in the file) and are filled from
 * the packed bytes the first time the grammar is used: see
 * cmake/Grammars.cmake and src/grammar_pack.c. The tables are mostly zeros,
 * so ~13 MB of md.exe become well under 1 MB. */
#include MD_PARSER_C

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <zstd.h>

int main(int argc, char **argv)
{
    if (argc != 4) {
        fprintf(stderr, "usage: ts_pack <out.c> <out.h> <id>\n");
        return 2;
    }
    const size_t a = sizeof ts_parse_table, b = sizeof ts_small_parse_table;
    unsigned char *raw = malloc(a + b);
    size_t cap = ZSTD_compressBound(a + b);
    unsigned char *packed = malloc(cap);
    if (!raw || !packed) return 1;
    memcpy(raw, ts_parse_table, a);
    memcpy(raw + a, ts_small_parse_table, b);
    size_t n = ZSTD_compress(packed, cap, raw, a + b, 19);
    if (ZSTD_isError(n)) {
        fprintf(stderr, "ts_pack: %s\n", ZSTD_getErrorName(n));
        return 1;
    }

    FILE *c = fopen(argv[1], "wb");
    if (!c) { perror(argv[1]); return 1; }
    fprintf(c, "/* Generated by tools/ts_pack.c: parse tables of the %s grammar,\n"
               " * zstd-compressed (%zu -> %zu bytes). */\n"
               "#include <stddef.h>\n"
               "const size_t md_ts_%s_pack_len = %zu;\n"
               "const unsigned char md_ts_%s_pack[] = {\n",
            argv[3], a + b, n, argv[3], n, argv[3]);
    for (size_t i = 0; i < n; ++i) {
        fprintf(c, "%u,%s", packed[i], i % 32 == 31 ? "\n" : "");
    }
    fprintf(c, "};\n");
    if (fclose(c) != 0) { perror(argv[1]); return 1; }

    FILE *h = fopen(argv[2], "wb");
    if (!h) { perror(argv[2]); return 1; }
    fprintf(h, "/* Generated by tools/ts_pack.c for the %s grammar. */\n"
               "#define MD_TS_SMALL_PARSE_TABLE_LEN %zu\n",
            argv[3], b / sizeof ts_small_parse_table[0]);
    if (fclose(h) != 0) { perror(argv[2]); return 1; }
    printf("ts_pack %s: parse tables %zu -> %zu bytes\n", argv[3], a + b, n);
    free(raw);
    free(packed);
    return 0;
}
